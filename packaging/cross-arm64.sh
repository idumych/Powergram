#!/bin/sh
# cross-arm64.sh - builds powergram-<version>-<revision>-arm64.hpkg on Linux,
# with the cross tools of a Haiku arm64 build tree.
#
# There is no TDLib, Opus or OGG for Haiku arm64 to install (HaikuPorts has
# no arm64 repository), so this builds them too: TDLib from source with the
# Haiku support in tools/patch-tdlib.py, Opus and OGG as static libraries
# linked into the app. The package needs only OpenSSL and zlib at run time.
#
#   HAIKU_GENERATED=/path/to/haiku/generated.arm64 sh packaging/cross-arm64.sh
#
# HAIKU_GENERATED is a Haiku arm64 build tree's output directory, configured
# with --cross-tools-source and --build-cross-tools arm64, after building an
# image (jam -q @minimum-raw or similar). From it come the compiler
# (cross-tools-arm64/bin), the host tools (rc, xres, mimeset, package) and,
# unless HAIKU_SYSROOT names one already made, a sysroot assembled from the
# haiku, haiku_devel and gcc_syslibs packages it built and the openssl3 and
# zlib packages in its download/ directory.
#
# Needs: cmake, gperf, a native C++ compiler (TDLib generates its sources with
# tools it builds first), git, curl. TDLib's largest files take 3-4 GB of
# memory each to compile; JOBS sets the parallel jobs (default: CPUs / 2).
# Everything is built under build/cross-arm64 and kept for the next run.
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)

GEN=${HAIKU_GENERATED:?set HAIKU_GENERATED to a Haiku arm64 build tree (generated.arm64)}
TRIPLE=aarch64-unknown-haiku
CROSS="$GEN/cross-tools-arm64/bin"
HOST=$(ls -d "$GEN"/objects/linux/*/release/tools | head -1)
W="$ROOT/build/cross-arm64"
SYSROOT=${HAIKU_SYSROOT:-$W/sysroot}
JOBS=${JOBS:-$(( $(nproc) / 2 > 0 ? $(nproc) / 2 : 1 ))}
# The TDLib commit this was built and tested with.
TD_COMMIT=${TD_COMMIT:-c8828d50f5eac2fc7089ce1089d7ce9095c61b5e}
OGG=libogg-1.3.5
OPUS=opus-1.5.2

for t in "$CROSS/$TRIPLE-g++" "$HOST/rc/rc" "$HOST/xres" "$HOST/mimeset" \
		"$HOST/package/package"; do
	[ -x "$t" ] || { echo "cross-arm64: $t not found" >&2; exit 1; }
done
mkdir -p "$W"

# 1. The sysroot: Haiku's headers and libraries, gcc's runtime libraries,
#    OpenSSL and zlib.
if [ ! -f "$SYSROOT/.done" ]; then
	# packages_build/<profile>/hpkg_-<package>.hpkg/contents
	P=""
	for d in "$GEN"/objects/haiku/arm64/packaging/packages_build/*; do
		if [ -d "$d/hpkg_-haiku_devel.hpkg/contents/develop" ] &&
				[ -d "$d/hpkg_-haiku.hpkg/contents/lib" ]; then
			P=$d; break
		fi
	done
	[ -n "$P" ] || {
		echo "cross-arm64: no haiku/haiku_devel package contents under $GEN; build an image first" >&2
		exit 1; }
	SYSLIBS=$(ls -d "$GEN"/build_packages/gcc_syslibs-*-arm64/lib | head -1)
	rm -rf "$SYSROOT"; mkdir -p "$SYSROOT/boot/system"
	cp -a "$P/hpkg_-haiku_devel.hpkg/contents/develop" "$SYSROOT/boot/system/"
	cp -a "$P/hpkg_-haiku.hpkg/contents/lib" "$SYSROOT/boot/system/"
	cp -a "$SYSLIBS"/. "$SYSROOT/boot/system/lib/"
	for p in openssl3 openssl3_devel zlib zlib_devel; do
		f=$(ls "$GEN"/download/${p}-[0-9]*-arm64.hpkg | head -1)
		"$HOST/package/package" extract -C "$SYSROOT/boot/system" "$f"
	done
	rm -f "$SYSROOT/boot/system/.PackageInfo"
	# gcc_syslibs has only the versioned libraries; the linker wants the
	# development names in develop/lib.
	for l in libstdc++ libgcc_s; do
		v=$(ls "$SYSROOT/boot/system/lib/$l.so."* 2>/dev/null | head -1)
		[ -z "$v" ] || ln -sfn "../../lib/$(basename "$v")" \
			"$SYSROOT/boot/system/develop/lib/$l.so"
	done
	touch "$SYSROOT/.done"
fi
DEV="$SYSROOT/boot/system/develop"

# A Haiku executable is a shared object, so everything is -fPIC; CMake adds
# -fPIE after the flags it is given, so a wrapper puts -fPIC last.
mkdir -p "$W/bin"
for t in gcc g++; do
	printf '#!/bin/sh\nexec %s --sysroot=%s "$@" -fPIC\n' \
		"$CROSS/$TRIPLE-$t" "$SYSROOT" > "$W/bin/$t"
	chmod +x "$W/bin/$t"
done
cat > "$W/toolchain.cmake" <<EOF
set(CMAKE_SYSTEM_NAME Haiku)
set(CMAKE_SYSTEM_PROCESSOR aarch64)
set(CMAKE_SYSROOT $SYSROOT)
set(CMAKE_C_COMPILER $W/bin/gcc)
set(CMAKE_CXX_COMPILER $W/bin/g++)
set(CMAKE_AR $CROSS/$TRIPLE-ar)
set(CMAKE_RANLIB $CROSS/$TRIPLE-ranlib)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
EOF

# 2. Opus and OGG, static.
PREFIX="$W/prefix"
for s in $OGG $OPUS; do
	[ -f "$W/$s.done" ] && continue
	case $s in libogg*) url=https://downloads.xiph.org/releases/ogg/$s.tar.gz ;;
		*) url=https://downloads.xiph.org/releases/opus/$s.tar.gz ;; esac
	[ -d "$W/$s" ] || curl -fsSL "$url" | tar xz -C "$W"
	rm -rf "$W/build-$s"; mkdir -p "$W/build-$s"
	(cd "$W/build-$s" &&
		cmake -DCMAKE_TOOLCHAIN_FILE="$W/toolchain.cmake" \
			-DCMAKE_BUILD_TYPE=Release -DBUILD_SHARED_LIBS=OFF \
			-DBUILD_TESTING=OFF -DCMAKE_INSTALL_PREFIX="$PREFIX" "$W/$s" >/dev/null &&
		cmake --build . -j "$JOBS" >/dev/null &&
		cmake --install . >/dev/null)
	touch "$W/$s.done"
done

# 3. TDLib, static. Its TL sources are generated by a native build first.
TD="$W/td"
if [ ! -d "$TD" ]; then
	git clone -q https://github.com/tdlib/td.git "$TD"
	git -C "$TD" checkout -q "$TD_COMMIT"
fi
python3 tools/patch-tdlib.py "$TD"
if [ ! -f "$TD/td/generate/auto/td/telegram/td_api.h" ]; then
	mkdir -p "$W/td-native"
	(cd "$W/td-native" &&
		cmake -DCMAKE_BUILD_TYPE=Release -DTD_GENERATE_SOURCE_FILES=ON "$TD" >/dev/null &&
		cmake --build . -j "$JOBS" >/dev/null)
fi
TDB="$W/td-arm64"
mkdir -p "$TDB"
(cd "$TDB" &&
	cmake -DCMAKE_TOOLCHAIN_FILE="$W/toolchain.cmake" -DCMAKE_CROSSCOMPILING=ON \
		-DCMAKE_BUILD_TYPE=MinSizeRel \
		-DOPENSSL_INCLUDE_DIR="$DEV/headers" \
		-DOPENSSL_SSL_LIBRARY="$DEV/lib/libssl.so" \
		-DOPENSSL_CRYPTO_LIBRARY="$DEV/lib/libcrypto.so" \
		-DZLIB_INCLUDE_DIR="$DEV/headers" -DZLIB_LIBRARY="$DEV/lib/libz.so" \
		"$TD" >/dev/null &&
	cmake --build . --target tdjson_static -j "$JOBS")

# 4. The app and the Deskbar add-on, with the Makefile's Haiku rules.
TD_LIBDIRS=""
for d in $(find "$TDB/" -name 'libtd*.a' -exec dirname {} \; | sort -u); do
	TD_LIBDIRS="$TD_LIBDIRS -L$d"
done
make clean >/dev/null
make -j "$JOBS" TARGET_OS=Haiku CXX="$W/bin/g++" \
	CXXFLAGS="-I$TD -I$TDB -I$TD/td/generate/auto -I$PREFIX/include" \
	LDFLAGS="-s $TD_LIBDIRS -L$PREFIX/lib" \
	RC="$HOST/rc/rc" XRES="$HOST/xres" MIMESET=true \
	Powergram obj/PowergramDeskbar

# 5. The package. Opus and OGG are linked in; there is no noto_emoji for
#    arm64 to require (emoji draw with the fonts the system has).
SKIP_BUILD=1 ARCH=arm64 \
	MIMESET="$HOST/mimeset --mimedb $GEN/objects/common/data/mime_db" \
	PACKAGE="$HOST/package/package" \
	HPKG_REQUIRES="lib:libssl lib:libcrypto lib:libz" \
	sh packaging/build-hpkg.sh
